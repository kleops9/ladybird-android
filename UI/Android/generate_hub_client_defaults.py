# Writes HubClientDefaults.h: a HubClientStub that does nothing for every message the Hub can send. The Android UI derives
# from it and overrides the messages it handles, so a message that upstream adds to HubClient.ipc doesn't break the build.

import re
import sys


def split_parameters(parameters):
    depth = 0
    current = ""
    for character in parameters:
        if character in "<([{":
            depth += 1
        elif character in ">)]}":
            depth -= 1
        if character == "," and depth == 0:
            yield current.strip()
            current = ""
        else:
            current += character
    if current.strip():
        yield current.strip()


def without_name(parameter):
    # "Vector<URL::URL> urls" -> "Vector<URL::URL>"
    match = re.match(r"^(.*?[\s&*>])([A-Za-z_][A-Za-z0-9_]*)$", parameter)
    return match.group(1).strip() if match else parameter


def main():
    endpoint_header, output = sys.argv[1], sys.argv[2]
    with open(endpoint_header) as file:
        source = file.read()

    stub = source[source.index("class HubClientStub : public IPC::Stub") :]
    declarations = re.findall(r"virtual (\S+) (\w+)\((.*?)\) = 0;", stub)

    lines = [
        "// Generated by UI/Android/generate_hub_client_defaults.py. Do not edit.",
        "",
        "#pragma once",
        "",
        "#include <Hub/HubClientEndpoint.h>",
        "",
        "namespace Ladybird {",
        "",
        "class HubClientDefaults : public HubClientStub {",
        "public:",
    ]
    for return_type, name, parameters in declarations:
        if return_type != "void":
            sys.exit(f"HubClient message {name} expects an answer, which the defaults can't give")
        types = ", ".join(without_name(parameter) for parameter in split_parameters(parameters))
        lines.append(f"    virtual void {name}({types}) override {{ }}")
    lines += ["};", "", "}", ""]

    with open(output, "w") as file:
        file.write("\n".join(lines))


if __name__ == "__main__":
    main()
